  async createFolder() {
    const name = prompt('Nome da nova pasta:');
    if (name && name.trim() && this.currentUserId()) {
      try {
        const newFolder = await this.supabaseService.createFolder(this.currentUserId()!, name.trim());
        this.folders.update(prev => [...prev, { id: newFolder.id, name: newFolder.name }]);
      } catch (e: any) {
        alert('Erro ao criar pasta: ' + e.message);
      }
    }
  }

  async deleteFolder(id: number, event: Event) {
    event.stopPropagation();
    if (id === 1) return; // Cannot delete favorites
    
    if (confirm('Tem a certeza? Os itens nesta pasta voltarão para "Todas".')) {
      try {
        await this.supabaseService.deleteFolder(id);
        // UI Update
        this.history.update(items => items.map(i => i.folderId === id ? { ...i, folderId: undefined } : i));
        this.folders.update(prev => prev.filter(f => f.id !== id));
        if (this.currentFolderId() === id) {
          this.currentFolderId.set('all');
        }
      } catch (e: any) {
        alert('Erro ao apagar pasta: ' + e.message);
      }
    }
  }

  selectFolder(id: string | number) {
    this.currentFolderId.set(id);
    if (window.innerWidth < 768) {
      this.isSidebarOpen.set(false);
    }
  }

  toggleMoveMenu(itemId: number, event: Event) {
    event.stopPropagation();
    if (this.movingItemId() === itemId) {
      this.movingItemId.set(null);
    } else {
      this.movingItemId.set(itemId);
    }
  }

  async moveItemToFolder(item: HistoryItem, folderId: number | 'all') {
    const finalId = folderId === 'all' ? null : folderId;
    
    try {
      await this.supabaseService.moveItemToFolder(item.id, finalId);
      
      this.history.update(prev => prev.map(i => {
        if (i.id === item.id) {
          return { ...i, folderId: finalId || undefined };
        }
        return i;
      }));
      this.movingItemId.set(null);
    } catch (e) {
      console.error(e);
    }
  }
  
  async deleteItem(item: HistoryItem, event: Event) {
    event.stopPropagation();
    if (confirm('Tem a certeza que deseja eliminar esta criação? Esta ação não pode ser desfeita.')) {
      try {
        await this.supabaseService.deleteHistoryItem(item.id);
        this.history.update(prev => prev.filter(i => i.id !== item.id));
        
        // Se o item apagado for o que está a ser visualizado/editado, limpar
        if (this.generatedUrl() === item.url) {
            this.generatedUrl.set(null);
            this.prompt.set('');
        }
      } catch (e: any) {
        alert('Erro ao eliminar: ' + e.message);
      }
    }
  }

  getFolderName(id: string | number): string {
    if (id === 'all') return 'Todas as Criações';
    const folder = this.folders().find(f => f.id === id);
    return folder ? folder.name : 'Desconhecida';
  }

  // --- EDITOR & GEN LOGIC ---

  toggleEditor() {
    if (this.currentTier() === 'free') {
      const wantUpgrade = confirm('A edição de imagem e vídeo é exclusiva para planos Básico e Profissional. Deseja ver os planos?');
      if (wantUpgrade) {
        this.activeTab.set('plans');
        window.scrollTo({ top: 0, behavior: 'smooth' });
      }
      return;
    }
    this.isEditing.update(v => !v);
    if (this.isEditing()) {
      this.editConfig.set({ brightness: 100, contrast: 100, saturate: 100, grayscale: 0, sepia: 0 });
    }
  }

  updateEditConfig(key: keyof EditConfig, event: Event) {
    const value = Number((event.target as HTMLInputElement).value);
    this.editConfig.update(prev => ({ ...prev, [key]: value }));
  }

  downloadEditedImage() {
    if (this.mediaType() !== 'image') {
      alert('Para vídeos, o download baixará o arquivo original.');
      const link = document.createElement('a');
      link.href = this.generatedUrl()!;
      link.download = 'video-editado.mp4';
      link.click();
      return;
    }
    const canvas = document.createElement('canvas');
    const ctx = canvas.getContext('2d');
    const img = this.imagePreviewRef.nativeElement;
    if (!ctx || !img) return;

    canvas.width = img.naturalWidth;
    canvas.height = img.naturalHeight;
    const c = this.editConfig();
    ctx.filter = `brightness(${c.brightness}%) contrast(${c.contrast}%) saturate(${c.saturate}%) grayscale(${c.grayscale}%) sepia(${c.sepia}%)`;
    ctx.drawImage(img, 0, 0, canvas.width, canvas.height);

    const link = document.createElement('a');
    link.download = `imagem-editada-${Date.now()}.jpg`;
    link.href = canvas.toDataURL('image/jpeg', 0.9);
    link.click();
  }

  appendTag(tag: string) {
    const current = this.prompt();
    if (current.toLowerCase().includes(tag.toLowerCase())) return;
    let separator = '';
    if (current.length > 0) {
      separator = !current.trim().endsWith(',') ? ', ' : ' ';
    }
    this.prompt.set(current + separator + tag);
  }

