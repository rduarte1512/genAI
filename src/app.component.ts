  toggleAuthMode() {
    this.isLoginMode.update(v => !v);
    this.loginError.set(null);
  }

  async onAuthAction() {
    const emailVal = this.email().trim();
    const passVal = this.password().trim();
    const nameVal = this.signupName().trim();

    if (!emailVal || !emailVal.includes('@')) {
      this.loginError.set('Email inválido.');
      return;
    }
    if (!passVal || passVal.length < 6) {
      this.loginError.set('A palavra-passe deve ter 6+ caracteres.');
      return;
    }

    this.loginError.set(null);
    this.isLoading.set(true);

    try {
      if (this.isLoginMode()) {
        const { user } = await this.supabaseService.signIn(emailVal, passVal);
        if (user) {
          this.currentUserId.set(user.id);
          this.isLoggedIn.set(true);
          await this.loadUserData(user.id);
        }
      } else {
        if (!nameVal) {
          this.loginError.set('Nome é obrigatório.');
          this.isLoading.set(false);
          return;
        }
        
        const data = await this.supabaseService.signUp(emailVal, passVal, nameVal);
        
        if (data.user && !data.session) {
           alert('Conta criada! Verifique o email para confirmar antes de entrar.');
           this.isLoginMode.set(true); 
        } else if (data.user && data.session) {
          this.currentUserId.set(data.user.id);
          this.isLoggedIn.set(true);
          await this.loadUserData(data.user.id);
          alert('Bem-vindo ao GenAI Studio!');
        }
      }
    } catch (err: any) {
      const errorMsg = err.message || '';
      
      // TRATAMENTO DE ERROS COMUNS
      if (errorMsg.includes('User already registered') || errorMsg.includes('already registered')) {
        this.loginError.set('Este email já está registado. A mudar para Login...');
        this.isLoginMode.set(true); 
      } else if (errorMsg.includes('Database error saving new user')) {
        this.loginError.set('Erro na Base de Dados. Provavelmente faltam as tabelas.');
        this.showSqlModal.set(true); // Abre o modal de ajuda automaticamente
      } else {
        this.loginError.set(errorMsg || 'Erro de autenticação.');
      }
    } finally {
      this.isLoading.set(false);
    }
  }

  async onLogout() {
    await this.supabaseService.signOut();
    this.isLoggedIn.set(false);
    this.currentUserId.set(null);
    this.email.set('');
    this.password.set('');
    this.history.set([]);
    this.folders.set([{ id: 1, name: 'Favoritos', icon: 'heart' }]);
    this.prompt.set('');
    this.generatedUrl.set(null);
    this.showLandingPage.set(true); // Return to landing page
  }

