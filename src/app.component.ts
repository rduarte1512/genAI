  closeCheckout() {
    if (this.isProcessingPayment()) return;
    this.showCheckout.set(false);
    this.checkoutItem.set(null);
  }

  async processPayment() {
    if (this.isProcessingPayment()) return;
    
    if (this.paymentMethod() === 'card') {
      if (!this.cardNumber() || !this.cardName()) {
        alert('Dados do cartão incompletos.');
        return;
      }
    }

    this.isProcessingPayment.set(true);
    await new Promise(resolve => setTimeout(resolve, 2000));

    const item = this.checkoutItem();
    const uid = this.currentUserId();

    if (item && uid) {
      try {
        if (item.type === 'credits') {
          const newCredits = this.credits() + item.credits;
          await this.supabaseService.updateCredits(uid, newCredits);
          this.credits.set(newCredits);
        } else if (item.type === 'plan') {
          // Simplification: Set credits to plan amount and update tier
          await this.supabaseService.updateTier(uid, item.id, item.credits);
          this.currentTier.set(item.id as PlanTier);
          this.credits.set(item.credits);
        }
        alert('Pagamento confirmado!');
      } catch (e: any) {
        alert('Erro ao processar na DB: ' + e.message);
      }
      this.activeTab.set('studio');
    }

    this.isProcessingPayment.set(false);
    this.closeCheckout();
  }

  // --- GENERATION ---

  calculateCost(): number {
    if (this.mediaType() === 'video') return 10;
    return Math.floor(Math.random() * (8 - 4 + 1)) + 4;
  }

  async onGenerate() {
    const currentPrompt = this.prompt().trim();
    if (!currentPrompt) {
      this.error.set('Por favor, digite um prompt.');
      return;
    }

    const cost = this.calculateCost();
    if (this.credits() < cost) {
      this.error.set(`Créditos insuficientes (${cost}).`);
      return;
    }

    this.error.set(null);
    this.generatedUrl.set(null);
    this.isLoading.set(true);
    this.isEditing.set(false);

    try {
      let url: string;
      if (this.mediaType() === 'image') {
        this.statusMessage.set(`A gerar imagem (${cost} créditos)...`);
        url = await this.geminiService.generateImage(currentPrompt);
      } else {
        this.statusMessage.set(`A gerar vídeo (${cost} créditos)...`);
        // Gemini service returns a blob URL for video
        url = await this.geminiService.generateVideo(currentPrompt);
      }

      this.generatedUrl.set(url);
      
      const userId = this.currentUserId();
      if (userId) {
        // Guardar na BD
        // Nota: Blob URLs de vídeo expiram. Base64 de vídeo é muito pesado para TEXT column.
        // O ideal é usar Supabase Storage, mas aqui guardamos a URL temporária ou Base64 se possível.
        let storageUrl = url;
        if (this.mediaType() === 'video') {
           // Em produção, farias upload do blob para Storage e guardarias a URL pública.
           storageUrl = "Vídeo gerado (Storage não configurado)"; 
        }

        const savedItem = await this.supabaseService.addToHistory(userId, this.mediaType(), currentPrompt, storageUrl, cost);
        this.history.update(prev => [savedItem, ...prev]);

        // Deduzir créditos
        const newCredits = this.credits() - cost;
        await this.supabaseService.updateCredits(userId, newCredits);
        this.credits.set(newCredits);
      }

    } catch (err: any) {
      this.error.set(err.message || 'Erro inesperado.');
    } finally {
      this.isLoading.set(false);
      this.statusMessage.set('');
    }
  }

  setMediaType(type: MediaType) {
    this.mediaType.set(type);
    this.error.set(null);
    this.generatedUrl.set(null);
    this.isEditing.set(false);
  }

  selectHistoryItem(item: HistoryItem) {
    this.prompt.set(item.prompt);
    this.mediaType.set(item.type);
    this.generatedUrl.set(item.url);
    this.error.set(null);
    this.activeTab.set('studio');
    this.isEditing.set(false);
    if (window.innerWidth < 768) {
      this.isSidebarOpen.set(false);
    }
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }

  get isFormValid(): boolean {
    return this.prompt().trim().length > 0;
  }
